"""Declared analysis of X1 (docs/three_experiments_declared_protocol.md): the 30 kHz baseline with set W.
Writes cache/baseline30k/summary.md. Usage: python -W ignore analyse_baseline_30k.py"""
import json

import numpy as np
from scipy.stats import t as student_t

from build_wide_tables import PARTS, channels_of
from config import CACHE_DIR
from feature_cost import model_cost

R = json.load(open(CACHE_DIR / "baseline30k" / "results.json"))
G = json.load(open(CACHE_DIR / "grid" / "grid_results.json"))
N = json.load(open(CACHE_DIR / "grid" / "networks_results.json"))
SHORT = {"P1_combined": "P1", "P2_combined": "P2", "Wallace_S1": "S1", "Wallace_S2": "S2"}
METHODS = ["LDA", "SVM", "RandomForest", "RBFNN_default", "RBFNN_tuned", "LSTM_default", "LSTM_tuned"]
PER_WINDOW = ["LDA", "SVM", "RandomForest", "RBFNN_default", "RBFNN_tuned"]
TC = student_t.ppf(0.975, 4)


def ref_key(part, rate, bits, method):
    n = len(channels_of(part))
    return f"{part}|{rate}Hz|{n}ch|{bits}bit|W|{method}"


def main():
    L = ["# X1: baseline on the full-rate stream (30 kHz, all channels, 16 bit, set W)\n",
         "Generated by analyse_baseline_30k.py from cache/baseline30k/results.json. Grouped 5-fold CV of the grid. Accuracy %, pooled over folds.\n"]
    L.append("## Accuracy (%) and Cohen's kappa\n")
    L.append("| Participant | bit rate | windows | " + " | ".join(METHODS) + " |\n|---|---|---|" + "---|" * len(METHODS))
    for p in PARTS:
        r0 = R[f"{p}|LDA"]
        L.append(f"| {SHORT[p]} | {r0['bitrate_bps'] / 1e6:.2f} Mb/s | {r0['n_windows']} | "
                 + " | ".join(f"{100 * R[f'{p}|{m}']['accuracy']:.1f} ({R[f'{p}|{m}']['cohen_kappa']:.3f})" for m in METHODS) + " |")
    L.append("| mean | | | " + " | ".join(f"{100 * np.mean([R[f'{p}|{m}']['accuracy'] for p in PARTS]):.1f}" for m in METHODS) + " |")
    L.append("\nWeighted F1 (%): " + "; ".join(f"{SHORT[p]} " + ", ".join(f"{m} {100 * R[f'{p}|{m}']['weighted_f1']:.1f}" for m in METHODS) for p in PARTS))

    L.append("\n## Secondary: causal hard vote over all decisions since the onset (%)\n")
    L.append("| Participant | LDA | SVM | RF | LSTM tuned (no vote) |\n|---|---|---|---|---|")
    for p in PARTS:
        L.append(f"| {SHORT[p]} | " + " | ".join(f"{100 * R[f'{p}|{m}']['vote_all']['accuracy']:.1f}" for m in ("LDA", "SVM", "RandomForest"))
                 + f" | {100 * R[f'{p}|LSTM_tuned']['accuracy']:.1f} |")

    L.append("\n## The two best per-window models, paired by fold (points; 95 % t-interval, 4 df)\n")
    for p in PARTS:
        ranked = sorted(PER_WINDOW, key=lambda m: -R[f"{p}|{m}"]["accuracy"])
        a, b = ranked[:2]
        d = 100 * (np.array(R[f"{p}|{a}"]["fold_accs"]) - np.array(R[f"{p}|{b}"]["fold_accs"]))
        h = TC * d.std(ddof=1) / np.sqrt(len(d))
        reading = "about equal" if abs(d.mean()) < 1 else ("resolved" if (d.mean() - h > 0) else "unresolved")
        L.append(f"- {SHORT[p]}: {a} minus {b} = {d.mean():+.2f} ± {h:.2f} ({reading})")

    L.append("\n## Against the 1 kHz reference (1 kHz, all channels, 16 bit, W) and 10 kHz (unpaired: windows differ between rates)\n")
    L.append("| Participant | Model | 30 kHz | 10 kHz (bits) | 1 kHz | 30 kHz − 1 kHz |\n|---|---|---|---|---|---|")
    for p in PARTS:
        for m in ("LDA", "SVM", "RandomForest", "RBFNN_tuned", "LSTM_default", "LSTM_tuned"):
            src = G if m in ("LDA", "SVM", "RandomForest") else N
            k1 = ref_key(p, 1000, 16, m)
            k10 = next((ref_key(p, 10000, b, m) for b in (16, 12, 8) if ref_key(p, 10000, b, m) in G), None) if src is G else None
            a30 = R[f"{p}|{m}"]["accuracy"]
            a1 = src.get(k1, {}).get("accuracy")
            a10 = G[k10]["accuracy"] if k10 else None
            ten = f"{100 * a10:.1f} ({k10.split('|')[3]})" if a10 is not None else "–"
            one = f"{100 * a1:.1f} | {100 * (a30 - a1):+.1f}" if a1 is not None else "not run (the grid's reference cell for S2 used 8 of 12 channels) | –"
            L.append(f"| {SHORT[p]} | {m} | {100 * a30:.1f} | {ten} | {one} |")
    d_all = [R[f"{p}|{m}"]["accuracy"] - G[ref_key(p, 1000, 16, m)]["accuracy"] for p in PARTS for m in ("LDA", "SVM", "RandomForest")]
    L.append(f"\nMean 30 kHz − 1 kHz over the four participants and LDA, SVM, RF: {100 * np.mean(d_all):+.2f} points (range {100 * min(d_all):+.1f} to {100 * max(d_all):+.1f}).")

    L.append("\n## Cost per decision at 30 kHz (analytic; same counting as the grid)\n")
    for p in PARTS:
        r = R[f"{p}|LDA"]
        ex = r["extraction"]["flops"]
        mc = model_cost("LDA", r["n_features"], len(r["class_labels"]))
        L.append(f"- {SHORT[p]}: {r['n_features']} features, extraction {ex / 1000:.0f} kFLOP per decision; LDA model {(mc['macs'] + mc['other_ops']) / 1000:.1f} k operations; "
                 f"grid at 1 kHz: extraction {G[ref_key(p, 1000, 16, 'LDA')]['extraction']['flops'] / 1000:.0f} kFLOP")
    L.append("\nSeconds per method (sum over participants): " + ", ".join(f"{m} {sum(R[f'{p}|{m}']['seconds'] for p in PARTS):.0f}" for m in METHODS))
    out = CACHE_DIR / "baseline30k" / "summary.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
