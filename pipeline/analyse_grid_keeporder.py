"""EXPLORATORY summary of run_grid_keeporder.py: the grid with the grid's channel order (published) against the keep order, set W, LDA/SVM/RF.
Cells whose channel set does not change are taken from cache/grid/grid_results.json for both. Nothing in cache/grid/ is changed.
Output: cache/grid_keeporder/summary.md and cache/grid_keeporder/fig_frontier_keeporder.pdf. Usage: python -W ignore analyse_grid_keeporder.py"""
import json

import numpy as np
import pandas as pd

from config import CACHE_DIR
from run_grid_keeporder import KEEP, OUT, OUT_DIR, configs

SHORT = {"P1_combined": "P1", "P2_combined": "P2", "Wallace_S1": "S1", "Wallace_S2": "S2"}
MODELS = ["LDA", "SVM", "RandomForest"]
G = json.load(open(CACHE_DIR / "grid" / "grid_results.json"))
K = json.load(open(OUT))


def frame(which):
    rows = []
    for k, v in G.items():
        part, r, n, b, s, m = k.split("|")
        if s != "W":
            continue
        rec = K.get(k, v) if which == "keep" else v
        rows.append(dict(part=part, rate=int(r[:-2]), ch=int(n[:-2]), bits=int(b[:-3]), model=m, acc=100 * rec["accuracy"],
                         kbps=int(r[:-2]) * int(n[:-2]) * int(b[:-3]) / 1000, chans=rec["channels"]))
    return pd.DataFrame(rows)


D = {"grid": frame("grid"), "keep": frame("keep")}
assert len(D["grid"]) == len(D["keep"])
out = ["# EXPLORATORY: bit-rate grid with the keep order of the channel-importance study (set W)", "",
       "Generated by analyse_grid_keeporder.py. 'grid' = published grid (channels in the grid's mutual-information order); 'keep' = same cells",
       "with channels in the backward-elimination keep order (docs/channel_importance_results.md). Only cells whose channel set changes were",
       "re-run (cache/grid_keeporder/results.json); all other cells are the published values. The keep order was chosen on the same participants",
       "(30 kHz, set W), so 'keep' is optimistic: a sensitivity check, not a replacement.", "",
       "Channel orders:", ""]
for p in SHORT:
    out.append(f"- {SHORT[p]}: grid {configs(p)[1][:len(KEEP[p])]}; keep {KEEP[p]}")

# 1. channel main effect and paired losses
out += ["", "## 1. Mean accuracy by channel count (mean over rates, bits and models; %)", "", "| Participant | Order | " +
        " | ".join(f"{n} ch" for n in (2, 5, 8, 12)) + " |", "|---|---|---|---|---|---|"]
for p in SHORT:
    for w in ("grid", "keep"):
        d = D[w][D[w].part == p]
        out.append(f"| {SHORT[p]} | {w} | " + " | ".join(f"{d[d.ch == n].acc.mean():.1f}" if (d.ch == n).any() else "" for n in (2, 5, 8, 12)) + " |")


def paired_loss(d, hi, lo):
    a = d[d.ch == hi].set_index(["rate", "bits", "model"]).acc
    b = d[d.ch == lo].set_index(["rate", "bits", "model"]).acc
    j = a.index.intersection(b.index)
    return float((a[j] - b[j]).mean()) if len(j) else None


out += ["", "## 2. Paired loss when channels are removed (points; paired at equal rate, bits and model, mean over pairs)", "",
        "| Participant | 5 to 2 (grid / keep) | 8 to 5 (grid / keep) | 12 to 8 (grid / keep) |", "|---|---|---|---|"]
for p in SHORT:
    cells = []
    for hi, lo in ((5, 2), (8, 5), (12, 8)):
        g, k = paired_loss(D["grid"][D["grid"].part == p], hi, lo), paired_loss(D["keep"][D["keep"].part == p], hi, lo)
        cells.append(f"{g:.1f} / {k:.1f}" if g is not None else "")
    out.append(f"| {SHORT[p]} | " + " | ".join(cells) + " |")

# 3. lowest bit rate reaching 90 and 95 %
out += ["", "## 3. Lowest bit rate reaching 90 % and 95 % accuracy, per model (kb/s, configuration rate/channels/bits)", "",
        "| Participant | Model | 90 %: grid | 90 %: keep | 95 %: grid | 95 %: keep |", "|---|---|---|---|---|---|"]


def lowest(d, target):
    d = d[d.acc >= target].sort_values(["kbps", "acc"], ascending=[True, False])
    if d.empty:
        return "not reached"
    r = d.iloc[0]
    return f"{r.kbps:g} ({r.rate} Hz, {r.ch} ch, {r.bits} b; {r.acc:.1f})"


for p in SHORT:
    for m in MODELS:
        g, k = (D[w][(D[w].part == p) & (D[w].model == m)] for w in ("grid", "keep"))
        out.append(f"| {SHORT[p]} | {m} | {lowest(g, 90)} | {lowest(k, 90)} | {lowest(g, 95)} | {lowest(k, 95)} |")

# 4. best accuracy within a bit-rate budget
BUD = [4, 8, 16, 32, 64, 128]
out += ["", "## 4. Best accuracy within a bit-rate budget (best cell of the best model; %), grid / keep", "",
        "| Participant | " + " | ".join(f"<= {b} kb/s" for b in BUD) + " |", "|---|" + "---|" * len(BUD)]
for p in SHORT:
    cells = []
    for b in BUD:
        g, k = (D[w][(D[w].part == p) & (D[w].kbps <= b)].acc.max() for w in ("grid", "keep"))
        cells.append(f"{g:.1f} / {k:.1f}" if not np.isnan(g) else "")
    out.append(f"| {SHORT[p]} | " + " | ".join(cells) + " |")
out.append("")
open(OUT_DIR / "summary.md", "w", encoding="utf-8").write("\n".join(out))
print("\n".join(out))

# figure: best accuracy (any model) against bit rate, Pareto frontier, grid vs keep order
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False})
fig, axs = plt.subplots(1, 4, figsize=(7.2, 2.4), sharey=True)
for ax, p in zip(axs, SHORT):
    for w, col, mk in (("grid", "#e07a1f", "s"), ("keep", "#2a6fdb", "o")):
        d = D[w][D[w].part == p].groupby("kbps").acc.max().sort_index()
        front = d.cummax()
        ax.step(front.index, front.values, where="post", color=col, lw=2, label=f"{'Grid' if w == 'grid' else 'Keep'} order")
        ax.plot(d.index, d.values, mk, color=col, ms=2.5, alpha=0.5)
    ax.set_xscale("log")
    ax.set_title(SHORT[p])
    ax.set_xlabel("Bit rate (kb/s)")
    ax.grid(axis="y", color="#dddddd", lw=0.6)
axs[0].set_ylabel("Best accuracy (%)")
axs[0].legend(frameon=False, fontsize=7, loc="lower right")
fig.tight_layout()
fig.savefig(OUT_DIR / "fig_frontier_keeporder.pdf")
print("figure ->", OUT_DIR / "fig_frontier_keeporder.pdf")
