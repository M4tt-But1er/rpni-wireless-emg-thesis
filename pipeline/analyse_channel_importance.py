"""Summary of run_channel_importance.py (docs/channel_importance_declared_protocol.md) -> cache/channel_importance/summary.md and
docs/thesis_sim/figures/fig_channel_importance.pdf. No hand-typed numbers. Usage: python -W ignore analyse_channel_importance.py"""
import json

import numpy as np
from scipy.stats import t as student_t

from config import CACHE_DIR
from run_channel_importance import MODELS, OUT_DIR, skey

E = json.load(open(OUT_DIR / "evals.json"))
P = json.load(open(OUT_DIR / "plan.json"))
SHORT = {"P1_combined": "P1", "P2_combined": "P2", "Wallace_S1": "S1", "Wallace_S2": "S2"}
TCRIT = student_t.ppf(0.975, 4)
FIG = CACHE_DIR.parent / "docs" / "thesis_sim" / "figures" / "fig_channel_importance.pdf"


def rec(part, sub, m):
    return E[f"{part}|{m}|{skey(part, sub)}"]


def acc(part, sub, m=None):
    return 100 * (rec(part, sub, m)["accuracy"] if m else np.mean([rec(part, sub, k)["accuracy"] for k in MODELS]))


def fold_mean(part, sub):
    return np.mean([rec(part, sub, k)["fold_accs"] for k in MODELS], axis=0)


def drop_ci(part, full, sub):
    d = 100 * (fold_mean(part, full) - fold_mean(part, sub))
    return acc(part, full) - acc(part, sub), TCRIT * d.std(ddof=1) / np.sqrt(len(d))


out = ["# Channel importance (E1 stream: 30 kHz, all implanted channels, 16 bit, set W)", "",
       "Generated by analyse_channel_importance.py from cache/channel_importance/. Protocol: docs/channel_importance_declared_protocol.md.",
       "Accuracy %, pooled over the grid's grouped 5-fold CV; 'mean' = mean of LDA, SVM and RF. LOCO loss = accuracy with all channels minus",
       "accuracy without the channel (mean model); ± = 95 % t-interval of the per-fold differences (4 df); * = interval excludes zero.",
       "Keep rank = position in the backward-elimination keep order (1 = kept longest); grid rank = position in the grid's channel order.", ""]

for part, p in P.items():
    ch, full = p["channels"], p["channels"]
    out += [f"## {SHORT[part]} ({len(ch)} channels, all channels: LDA {acc(part, full, 'LDA'):.1f}, SVM {acc(part, full, 'SVM'):.1f}, "
            f"RF {acc(part, full, 'RandomForest'):.1f}, mean {acc(part, full):.1f})", "",
            "| Channel | Type | Alone (mean) | Alone LDA / SVM / RF | LOCO loss (mean) | LOCO loss LDA / SVM / RF | Keep rank | Grid rank |",
            "|---|---|---|---|---|---|---|---|"]
    rows = []
    for c in ch:
        sub = [x for x in ch if x != c]
        d, h = drop_ci(part, full, sub)
        star = "*" if abs(d) > h else ""
        per = " / ".join(f"{acc(part, full, m) - acc(part, sub, m):+.1f}" for m in MODELS)
        alone = " / ".join(f"{acc(part, [c], m):.1f}" for m in MODELS)
        rows.append((p["be_keep_order"].index(c) + 1, f"| {c} | {'RPNI' if c in p['rpni'] else 'muscle'} | {acc(part, [c]):.1f} | {alone} | "
                     f"{d:+.1f} ± {h:.1f}{star} | {per} | {p['be_keep_order'].index(c) + 1} | {p['grid_order'].index(c) + 1} |"))
    out += [r for _, r in sorted(rows)] + [""]
    be = dict((n, a) for n, a in p["be_curve"])
    out += ["Accuracy (mean model) against channels kept: backward elimination (optimistic, chosen on the scoring folds) / grid order:", "",
            "| Channels kept | " + " | ".join(str(n) for n in range(1, len(ch) + 1)) + " |", "|---|" + "---|" * len(ch),
            "| Backward elimination | " + " | ".join(f"{100 * be[n]:.1f}" for n in range(1, len(ch) + 1)) + " |",
            "| Grid order | " + " | ".join(f"{acc(part, p['grid_order'][:n]):.1f}" for n in range(1, len(ch) + 1)) + " |", ""]
    within = min(n for n in range(1, len(ch) + 1) if 100 * be[n] >= acc(part, full) - 1.0)
    out += [f"Smallest backward-elimination subset within 1 point of all channels (descriptive, optimistic): {within} channels, "
            f"{p['be_keep_order'][:within]}.", ""]

out += ["## RPNI group test", "",
        "Loss = all channels minus the subset (mean model). Control = every way of removing as many intramuscular channels as there are RPNIs.",
        "", "| Participant | RPNI / muscle | All | RPNI removed: loss | Control: mean loss (range) | RPNI only | Verdict |", "|---|---|---|---|---|---|---|"]
for part, p in P.items():
    ch, rp = p["channels"], p["rpni"]
    mus = [c for c in ch if c not in rp]
    a = acc(part, ch)
    lr = a - acc(part, mus)
    lc = [a - acc(part, s.split("+")) for s in p["controls"]]
    verdict = "RPNI more informative" if lr > max(lc) else "RPNI less informative" if lr < min(lc) else "within control range"
    out.append(f"| {SHORT[part]} | {len(rp)} / {len(mus)} | {a:.1f} | {lr:+.1f} | {np.mean(lc):+.1f} ({min(lc):+.1f} to {max(lc):+.1f}) | "
               f"{acc(part, rp):.1f} | {verdict} |")
out.append("")
open(OUT_DIR / "summary.md", "w", encoding="utf-8").write("\n".join(out))
print("\n".join(out))

# figure: accuracy against channels kept, backward elimination vs grid order, one panel per participant
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False})
fig, axs = plt.subplots(1, 4, figsize=(7.2, 2.3), sharey=True)
for ax, (part, p) in zip(axs, P.items()):
    n = np.arange(1, len(p["channels"]) + 1)
    be = dict((k, a) for k, a in p["be_curve"])
    ax.plot(n, [100 * be[k] for k in n], "-o", color="#2a6fdb", lw=2, ms=4, label="Backward elimination")
    ax.plot(n, [acc(part, p["grid_order"][:k]) for k in n], "-s", color="#e07a1f", lw=2, ms=4, label="Grid order")
    ax.set_title(SHORT[part])
    ax.set_xlabel("Channels kept")
    ax.set_xticks(n[::2] if len(n) > 8 else n)
    ax.grid(axis="y", color="#dddddd", lw=0.6)
axs[0].set_ylabel("Mean accuracy (%)")
axs[0].legend(frameon=False, fontsize=7, loc="lower right")
fig.tight_layout()
fig.savefig(FIG)
print("figure ->", FIG)
