"""EXPLORATORY summary: the E4 family ablation with RF next to the published LDA and SVM (compare_family_ablation.py's own
paired-difference functions, with the RF cells of cache/family_ablation_rf/results.json added in memory; no file in cache/ is changed).
Output: cache/family_ablation_rf/summary.md. Usage: STAGE1_TAG=fixedrange python -W ignore analyse_family_ablation_rf.py"""
import json

import numpy as np
import pandas as pd

import compare_family_ablation as CF
from build_wide_tables import table_path
from config import CACHE_DIR
from families import LEAVES, MULTI_LEAF_BRANCHES, leaf_of

OUT_DIR = CACHE_DIR / "family_ablation_rf"
RF = json.load(open(OUT_DIR / "results.json"))
CF.R.update(RF)                                                     # in memory only
MODELS = ["LDA", "SVM", "RandomForest"]
SH = {"LDA": "LDA", "SVM": "SVM", "RandomForest": "RF"}

cols = list(pd.read_parquet(table_path("P1_combined", "ref")).columns[5:])
ncol = {l: sum(leaf_of(c) == l for c in cols) for l in LEAVES}
out = ["# EXPLORATORY: E4 family ablation with Random Forest", "",
       "Generated by analyse_family_ablation_rf.py. LDA and SVM: published cells (cache/family_ablation_results.json); RF: new cells",
       "(cache/family_ablation_rf/results.json), same 28 subsets, 8 tables (4 participants x ref/low streams) and folds.",
       "Mean paired difference over the 8 tables (points); 'res +/-' = tables where the 95 % fold interval excludes zero (better/worse).",
       "The wide set W was chosen by an LDA-only rule, so these RF results do not change W.", ""]

# reference accuracies
out += ["## Sets A and C (mean pooled accuracy over the 8 tables, %)", "", "| Set | LDA | SVM | RF |", "|---|---|---|---|"]
for s in ("A", "C"):
    out.append(f"| {s} | " + " | ".join(f"{100 * np.mean([CF.cell(p, o, s, m)['accuracy'] for p, o in CF.TABLES]):.1f}" for m in MODELS) + " |")

# check against Stage 1
s1 = json.load(open(CACHE_DIR / "stage1_ops_results_fixedrange.json"))
diff = [abs(RF[f"{p}|{o}|{s}|RandomForest"]["accuracy"] - s1[f"{p}|{o}"][f"{s}|RandomForest"]["accuracy"]) for p, o in CF.TABLES for s in ("A", "C")]
out += ["", f"Check: RF sets A and C against the Stage-1 RF cells (same tables and folds): {sum(d == 0 for d in diff)} of {len(diff)} identical, "
        f"largest difference {100 * max(diff):.3f} points.", ""]


def block(title, items, kind):
    ref = "C" if kind == "drop" else "A"
    rows = [f"## {title}", "", "| Family | Columns (P1 ref) | " + " | ".join(f"{SH[m]} mean | {SH[m]} res +/-" for m in MODELS) + " |",
            "|---|---|" + "---|---|" * len(MODELS)]
    vals = {}
    for name in items:
        cells = []
        for m in MODELS:
            d, n, rp, rn = CF.agg(f"{kind}:{name}", ref, m)
            vals[(name, m)] = d
            cells += [f"{d:+.2f}", f"{rp}/{rn}"]
        rows.append(f"| {name} | {ncol.get(name, '')} | " + " | ".join(cells) + " |")
    return rows + [""], vals


r1, drop = block("Drop one family from C (negative = the family was useful)", LEAVES, "drop")
r2, add = block("Add one family to A (positive = the family adds information)", LEAVES, "add")
r3, _ = block("Drop a whole branch from C", MULTI_LEAF_BRANCHES, "drop")
r4, _ = block("Add a whole branch to A", MULTI_LEAF_BRANCHES, "add")
out += r1 + r2 + r3 + r4

# agreement with the published labels (rule from the protocol, applied per model)
out += ["## Does RF agree with LDA and SVM?", "",
        "Protocol labels: dispensable = |mean drop| <= 0.3; useful = mean add >= +0.5 (published: both LDA and SVM). Here per model.", "",
        "| Family | LDA, SVM label | dispensable for RF | useful for RF |", "|---|---|---|---|"]
for l in LEAVES:
    lab = CF.label(drop[(l, "LDA")], drop[(l, "SVM")], add[(l, "LDA")], add[(l, "SVM")])
    out.append(f"| {l} | {lab} | {'yes' if abs(drop[(l, 'RandomForest')]) <= 0.3 else 'no'} ({drop[(l, 'RandomForest')]:+.2f}) | "
               f"{'yes' if add[(l, 'RandomForest')] >= 0.5 else 'no'} ({add[(l, 'RandomForest')]:+.2f}) |")
W = json.load(open(CACHE_DIR / "wide_set_W.json"))["kept_leaves"]
out += ["", f"Families kept in W (LDA rule): {', '.join(W)}.", "",
        f"RF run time: {sum(v['seconds'] for v in RF.values()) / 60:.0f} core-minutes over {len(RF)} cells.", ""]
open(OUT_DIR / "summary.md", "w", encoding="utf-8").write("\n".join(out))
print("\n".join(out))
